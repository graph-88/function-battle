// ============================================================
// スキャンビーム命中判定
// ============================================================

function checkScanHit(func){

    // ========================================================
    // 小型拠点
    // ========================================================

    points.forEach(
        point => {

            // ------------------------------------------------
            // すでに発見済み
            // ------------------------------------------------

            if(point.visible){

                return;

            }


            // ------------------------------------------------
            // x = ○ のビーム
            // 小型拠点から±2以内
            // ------------------------------------------------

            if(
                Math.abs(
                    point.x - func.x
                ) <= 2
            ){

                point.visible = true;

                point.scanned = true;

            }

        }
    );


    // ========================================================
    // 大型拠点
    // ========================================================

    largeBases.forEach(
        base => {

            // ------------------------------------------------
            // すでに発見済み
            // ------------------------------------------------

            if(base.visible){

                return;

            }


            const xs =
                base.points.map(
                    p => p.x
                );


            const minX =
                Math.min(...xs);

            const maxX =
                Math.max(...xs);


            // ------------------------------------------------
            // 縦線が大型拠点の横方向の範囲に入る
            // ------------------------------------------------

            if(
                func.x >= minX &&
                func.x <= maxX
            ){

                base.visible = true;

            }

        }
    );

}


