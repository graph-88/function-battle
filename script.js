// ============================================================
// 反比例による大型拠点発見
// ============================================================

function checkInverseLargeHit(func){

    largeBases.forEach(
        base => {

            // ------------------------------------------------
            // すでに発見済み
            // ------------------------------------------------

            if(base.visible){

                return;

            }


            // =================================================
            // 大型拠点の範囲
            // =================================================

            const xs =
                base.points.map(
                    p => p.x
                );


            const ys =
                base.points.map(
                    p => p.y
                );


            const minX =
                Math.min(...xs);

            const maxX =
                Math.max(...xs);

            const minY =
                Math.min(...ys);

            const maxY =
                Math.max(...ys);


            let hit = false;


            // =================================================
            // 反比例曲線が大型拠点に触れるか確認
            // =================================================

            for(
                let x = minX;
                x <= maxX;
                x += 0.01
            ){

                // x = 0 は定義できない

                if(
                    Math.abs(x) < 0.001
                ){

                    continue;

                }


                const y =
                    func.a / x +
                    func.b;


                if(
                    y >= minY &&
                    y <= maxY
                ){

                    hit = true;

                    break;

                }

            }


            // =================================================
            // 発見
            // =================================================

            if(hit){

                base.visible = true;

            }

        }
    );

}


