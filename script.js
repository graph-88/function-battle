// ============================================================
// 数値解析
// ============================================================

// ------------------------------------------------------------
// 整数・小数・分数を数値に変換
//
// 例
// 1       → 1
// -2      → -2
// 0.5     → 0.5
// 1/2     → 0.5
// -3/4    → -0.75
// ------------------------------------------------------------

function parseNumber(value){

    value =
        String(value).trim();


    // --------------------------------------------------------
    // 分数
    // --------------------------------------------------------

    if(value.includes("/")){

        const parts =
            value.split("/");


        if(parts.length !== 2){

            return NaN;

        }


        const numerator =
            Number(parts[0]);

        const denominator =
            Number(parts[1]);


        if(
            !Number.isFinite(numerator) ||
            !Number.isFinite(denominator) ||
            denominator === 0
        ){

            return NaN;

        }


        return numerator / denominator;

    }


    // --------------------------------------------------------
    // 整数・小数
    // --------------------------------------------------------

    return Number(value);

}


// ============================================================
// 関数解析
// ============================================================

function parseFunction(text){

    text =
        text.replace(/\s/g, "");


    const result =
        text.match(
            /^y=([+-]?(?:\d+(?:\/\d+)?|\d*\.\d+))x([+-](?:\d+(?:\/\d+)?|\d*\.\d+))$/
        );


    if(!result){

        return null;

    }


    const a =
        parseNumber(result[1]);

    const b =
        parseNumber(result[2]);


    if(
        !Number.isFinite(a) ||
        !Number.isFinite(b)
    ){

        return null;

    }


    return {

        a: a,

        b: b

    };

}


