// ============================================================
// 小型拠点配置
// ============================================================

function placePoint(event){

    if(!placing){

        return;

    }


    // ========================================================
    // 個数制限
    // ========================================================

    if(
        points.length >=
        MAX_SMALL
    ){

        alert(
            `小型拠点は${MAX_SMALL}個までです`
        );

        return;

    }


    // ========================================================
    // 座標取得
    // ========================================================

    const rect =
        canvas.getBoundingClientRect();


    const mx =
        event.clientX -
        rect.left;


    const my =
        event.clientY -
        rect.top;


    const x =
        Math.round(
            (mx - CENTER) /
            STEP
        );


    const y =
        Math.round(
            (CENTER - my) /
            STEP
        );


    // ========================================================
    // 範囲
    // ========================================================

    if(
        x < -10 ||
        x > 10 ||
        y < -10 ||
        y > 10
    ){

        return;

    }


    // ========================================================
    // 同じ場所禁止
    // ========================================================

    if(
        points.some(
            point =>
                point.x === x &&
                point.y === y
        )
    ){

        return;

    }


    // ========================================================
    // 大型拠点との重複禁止
    // ========================================================

    const insideLargeBase =
        largeBases.some(
            base => {

                const xs =
                    base.points.map(
                        point =>
                            point.x
                    );


                const ys =
                    base.points.map(
                        point =>
                            point.y
                    );


                const minX =
                    Math.min(...xs);

                const maxX =
                    Math.max(...xs);

                const minY =
                    Math.min(...ys);

                const maxY =
                    Math.max(...ys);


                return (
                    x >= minX &&
                    x <= maxX &&
                    y >= minY &&
                    y <= maxY
                );

            }
        );


    if(insideLargeBase){

        alert(
            "大型拠点の中には小型拠点を配置できません"
        );

        return;

    }


    // ========================================================
    // 小型拠点追加
    // ========================================================

    points.push({

        x: x,

        y: y,

        type: "small",

        destroyed: false,

        visible: true,

        scanned: false

    });


    // ========================================================
    // 表示更新
    // ========================================================

    const count =
        document.getElementById(
            "placeCount"
        );


    if(count){

        count.textContent =
            `小型拠点：${points.length} / ${MAX_SMALL}`;

    }


    updateFinishButton();

    drawGrid();

}


// ============================================================
// 大型拠点配置
// ============================================================

function placeLargeBase(event){

    // ========================================================
    // 個数制限
    // ========================================================

    if(
        largeBases.length >=
        MAX_LARGE
    ){

        placingLarge =
            false;

        largeStart =
            null;


        updateFinishButton();

        drawGrid();

        return;

    }


    // ========================================================
    // 座標取得
    // ========================================================

    const rect =
        canvas.getBoundingClientRect();


    const mx =
        event.clientX -
        rect.left;


    const my =
        event.clientY -
        rect.top;


    const x =
        Math.round(
            (mx - CENTER) /
            STEP
        );


    const y =
        Math.round(
            (CENTER - my) /
            STEP
        );


    // ========================================================
    // 範囲
    // ========================================================

    if(
        x < -10 ||
        x > 10 ||
        y < -10 ||
        y > 10
    ){

        return;

    }


    // ========================================================
    // 1点目
    // ========================================================

    if(largeStart === null){

        largeStart = {

            x: x,

            y: y

        };


        drawGrid();

        return;

    }


    // ========================================================
    // 2点目
    // ========================================================

    const end = {

        x: x,

        y: y

    };


    // ========================================================
    // サイズ
    // ========================================================

    const width =
        Math.abs(
            end.x -
            largeStart.x
        );


    const height =
        Math.abs(
            end.y -
            largeStart.y
        );


    if(
        width < 1 ||
        height < 1
    ){

        alert(
            "大型拠点は1×1以上にしてください"
        );


        largeStart =
            null;


        drawGrid();

        return;

    }


    // ========================================================
    // 四隅
    // ========================================================

    const x1 =
        Math.min(
            largeStart.x,
            end.x
        );


    const x2 =
        Math.max(
            largeStart.x,
            end.x
        );


    const y1 =
        Math.min(
            largeStart.y,
            end.y
        );


    const y2 =
        Math.max(
            largeStart.y,
            end.y
        );


    // ========================================================
    // 小型拠点との重複禁止
    // ========================================================

    const overlapSmall =
        points.some(
            point => {

                return (
                    point.x >= x1 &&
                    point.x <= x2 &&
                    point.y >= y1 &&
                    point.y <= y2
                );

            }
        );


    if(overlapSmall){

        alert(
            "小型拠点が存在する場所には大型拠点を配置できません"
        );


        largeStart =
            null;


        drawGrid();

        return;

    }
// ========================================================
// 他の大型拠点との重複禁止
// ========================================================

const overlapsLarge =
    largeBases.some(
        base => {

            const baseXs =
                base.points.map(
                    point => point.x
                );

            const baseYs =
                base.points.map(
                    point => point.y
                );

            const baseMinX =
                Math.min(...baseXs);

            const baseMaxX =
                Math.max(...baseXs);

            const baseMinY =
                Math.min(...baseYs);

            const baseMaxY =
                Math.max(...baseYs);


            // 四角形同士が重なっているか
            return !(
                x2 < baseMinX ||
                x1 > baseMaxX ||
                y2 < baseMinY ||
                y1 > baseMaxY
            );

        }
    );


if(overlapsLarge){

    alert(
        "他の大型拠点と重なるため配置できません"
    );

    largeStart =
        null;

    drawGrid();

    return;
}

    // ========================================================
    // 大型拠点作成
    // ========================================================

    largeBases.push({

        type: "large",

        points: [

            {
                x: x1,
                y: y1,
                hit: false
            },

            {
                x: x2,
                y: y1,
                hit: false
            },

            {
                x: x1,
                y: y2,
                hit: false
            },

            {
                x: x2,
                y: y2,
                hit: false
            }

        ],

        destroyed: false,

        visible: false

    });


    // ========================================================
    // 次の大型拠点
    // ========================================================

    largeStart =
        null;


    if(
        largeBases.length <
        MAX_LARGE
    ){

        placingLarge =
            true;

    }else{

        placingLarge =
            false;

    }


    // ========================================================
    // 表示更新
    // ========================================================

    const count =
        document.getElementById(
            "largePlaceCount"
        );


    if(count){

        count.textContent =
            `大型拠点：${largeBases.length} / ${MAX_LARGE}`;

    }


    updateFinishButton();

    drawGrid();

}


