// 一次関数ビーム発射
// ============================================================

function fireBeam(){

    // --------------------------------------------------------
    // 入力値
    // --------------------------------------------------------

    const a =
        parseNumber(
            document.getElementById("a").value
        );


    const b =
        parseNumber(
            document.getElementById("b").value
        );


    // --------------------------------------------------------
    // 数値チェック
    // --------------------------------------------------------

    if(
        !Number.isFinite(a) ||
        !Number.isFinite(b)
    ){

        alert(
            "数値を入力してください"
        );

        return;

    }


    // --------------------------------------------------------
    // a = 0 禁止
    // --------------------------------------------------------

    if(a === 0){

        alert(
            "傾き0のビームは使用できません"
        );

        return;

    }


    const func = {

        a: a,

        b: b

    };


    // --------------------------------------------------------
    // 同じ式か確認
    // --------------------------------------------------------

    const sameShot =
        shots.some(
            shot =>
                (!shot.type ||
                 shot.type === "linear") &&
                shot.a === func.a &&
                shot.b === func.b
        );


    // --------------------------------------------------------
    // 同じ式
    // ターン消費なし
    // --------------------------------------------------------

if(sameShot){

    checkHit(func);

    updateScore();

    checkAllBasesDestroyed();

    drawGrid();

    return;

}

    // --------------------------------------------------------
    // 同じ傾き5回制限
    // --------------------------------------------------------

    const slopeCount =
        shots.filter(
            shot =>
                (!shot.type ||
                 shot.type === "linear") &&
                shot.a === func.a
        ).length;


    if(slopeCount >= 5){

        alert(
            "同じ傾きのビームは5回までです"
        );

        return;

    }


// --------------------------------------------------------
// 1ターン消費できるか確認
// --------------------------------------------------------

if(!useTurn(1)){

    return;

}


// --------------------------------------------------------
// 新しいビーム
// --------------------------------------------------------

beams.push(
    func
);

shots.push(
    func
);


// --------------------------------------------------------
// 命中判定
// --------------------------------------------------------

checkHit(func);


// --------------------------------------------------------
// 得点
// --------------------------------------------------------

updateScore();


// --------------------------------------------------------
// すべての拠点を破壊したか確認
// --------------------------------------------------------

checkAllBasesDestroyed();


    // --------------------------------------------------------
    // 発射履歴
    // --------------------------------------------------------

    updateShotList();


    // --------------------------------------------------------
    // 再描画
    // --------------------------------------------------------

    drawGrid();

}


