// ============================================================
// すべての拠点を破壊したか確認
// ============================================================

function checkAllBasesDestroyed(){

    // --------------------------------------------------------
    // 小型拠点
    // --------------------------------------------------------

    const allSmallDestroyed =
        points.every(
            point =>
                point.destroyed
        );


    // --------------------------------------------------------
    // 大型拠点
    // --------------------------------------------------------

    const allLargeDestroyed =
        largeBases.every(
            base =>
                base.destroyed
        );


    // --------------------------------------------------------
    // すべて破壊
    // --------------------------------------------------------

    if(
        allSmallDestroyed &&
        allLargeDestroyed &&
        !gameEnded
    ){

        gameEnded =
            true;


        alert(
            `すべての拠点を破壊しました！\n` +
            `使用ターン数：${turn}`
        );


        return true;

    }


    return false;

}

// ============================================================
// ゲーム画面描画
// ============================================================

function drawGrid(){

    ctx.clearRect(
        0,
        0,
        SIZE,
        SIZE
    );


    // ========================================================
    // 背景
    // ========================================================

    ctx.fillStyle =
        "#080808";


    ctx.fillRect(
        0,
        0,
        SIZE,
        SIZE
    );


    // ========================================================
    // 方眼
    // ========================================================

    ctx.strokeStyle =
        "#333";

    ctx.lineWidth =
        1;


    for(
        let i = 0;
        i <= 20;
        i++
    ){

        const p =
            i * STEP;


        // 縦線

        ctx.beginPath();

        ctx.moveTo(
            p,
            0
        );

        ctx.lineTo(
            p,
            SIZE
        );

        ctx.stroke();


        // 横線

        ctx.beginPath();

        ctx.moveTo(
            0,
            p
        );

        ctx.lineTo(
            SIZE,
            p
        );

        ctx.stroke();

    }


    // ========================================================
    // 軸
    // ========================================================

    ctx.strokeStyle =
        "white";

    ctx.lineWidth =
        2;


    // y軸

    ctx.beginPath();

    ctx.moveTo(
        CENTER,
        0
    );

    ctx.lineTo(
        CENTER,
        SIZE
    );

    ctx.stroke();


    // x軸

    ctx.beginPath();

    ctx.moveTo(
        0,
        CENTER
    );

    ctx.lineTo(
        SIZE,
        CENTER
    );

    ctx.stroke();


    // ========================================================
    // 矢印
    // ========================================================

    drawArrow(
        CENTER,
        0,
        0
    );


    drawArrow(
        CENTER,
        SIZE,
        Math.PI
    );


    drawArrow(
        0,
        CENTER,
        -Math.PI / 2
    );


    drawArrow(
        SIZE,
        CENTER,
        Math.PI / 2
    );


    // ========================================================
    // 目盛り
    // ========================================================

    ctx.fillStyle =
        "white";

    ctx.font =
        "18px sans-serif";

    ctx.textAlign =
        "center";

    ctx.textBaseline =
        "middle";


    [
        -10,
        -5,
        5,
        10
    ].forEach(
        n => {

            const x =
                CENTER +
                n * STEP;


            const y =
                CENTER -
                n * STEP;


            // ------------------------------------------------
            // x軸目盛り
            // ------------------------------------------------

            ctx.beginPath();

            ctx.moveTo(
                x,
                CENTER - 8
            );

            ctx.lineTo(
                x,
                CENTER + 8
            );

            ctx.stroke();


            let xLabel =
                x;


            if(n === -10){

                xLabel += 12;

            }


            if(n === 10){

                xLabel -= 12;

            }


            ctx.fillText(
                n,
                xLabel,
                CENTER + 28
            );


            // ------------------------------------------------
            // y軸目盛り
            // ------------------------------------------------

            ctx.beginPath();

            ctx.moveTo(
                CENTER - 8,
                y
            );

            ctx.lineTo(
                CENTER + 8,
                y
            );

            ctx.stroke();


            ctx.fillText(
                n,
                CENTER - 28,
                y
            );

        }
    );


    // ========================================================
    // ビーム
    // ========================================================

    drawBeams();


    // ========================================================
    // 原点
    // ========================================================

    ctx.fillStyle =
        "white";


    ctx.fillText(
        "0",
        CENTER - 18,
        CENTER + 22
    );


    // ========================================================
    // 拠点
    // ========================================================

    drawPoints();


    // ========================================================
    // 大型拠点配置中
    // 1点目
    // ========================================================

    if(
        placingLarge &&
        largeStart !== null
    ){

        drawPoint(
            largeStart,
            "blue"
        );

    }

}


// ============================================================
// 矢印
// ============================================================

function drawArrow(
    x,
    y,
    angle
){

    ctx.save();


    ctx.translate(
        x,
        y
    );


    ctx.rotate(
        angle
    );


    ctx.fillStyle =
        "white";


    ctx.beginPath();


    ctx.moveTo(
        0,
        0
    );


    ctx.lineTo(
        -8,
        14
    );


    ctx.lineTo(
        8,
        14
    );


    ctx.closePath();


    ctx.fill();


    ctx.restore();

}


// ============================================================
// 点を描画
// ============================================================

function drawPoint(
    point,
    color
){

    const px =
        CENTER +
        point.x * STEP;


    const py =
        CENTER -
        point.y * STEP;


    ctx.beginPath();


    ctx.arc(
        px,
        py,
        8,
        0,
        Math.PI * 2
    );


    ctx.fillStyle =
        color;


    ctx.fill();

}


// ============================================================
// ビーム描画
// ============================================================

function drawBeams(){

    ctx.lineWidth =
        3;


    // ========================================================
    // 一次関数ビーム
    // ========================================================

    beams.forEach(
        func => {

            const shotIndex =
                shots.indexOf(func);


            // ------------------------------------------------
            // 選択中なら緑
            // ------------------------------------------------

            if(
                shotIndex === selectedShot
            ){

                ctx.strokeStyle =
                    "lime";

            }else{

                ctx.strokeStyle =
                    "red";

            }


            ctx.beginPath();


            let started =
                false;


            for(
                let x = -10;
                x <= 10;
                x += 0.01

            ){

                const y =
                    func.a * x +
                    func.b;


                if(
                    y < -10 ||
                    y > 10
                ){

                    continue;

                }


                const px =
                    CENTER +
                    x * STEP;


                const py =
                    CENTER -
                    y * STEP;


                if(!started){

                    ctx.moveTo(
                        px,
                        py
                    );

                    started = true;

                }else{

                    ctx.lineTo(
                        px,
                        py
                    );

                }

            }


            if(started){

                ctx.stroke();

            }

        }
    );


    // ========================================================
    // 反比例ビーム
    // ========================================================

    inverseBeams.forEach(
        func => {

            const shotIndex =
                shots.indexOf(func);


            if(
                shotIndex === selectedShot
            ){

                ctx.strokeStyle =
                    "lime";

            }else{

                ctx.strokeStyle =
                    "red";

            }


            ctx.beginPath();


            let started =
                false;


            for(
                let x = -10;
                x <= 10;
                x += 0.02
            ){

                // ------------------------------------------------
                // x = 0
                // ------------------------------------------------

                if(
                    Math.abs(x) < 0.001
                ){

                    started = false;

                    continue;

                }


                const y =
                    func.a / x +
                    func.b;


                // ------------------------------------------------
                // 範囲外なら線を切る
                // ------------------------------------------------

                if(
                    y < -10 ||
                    y > 10
                ){

                    started = false;

                    continue;

                }


                const px =
                    CENTER +
                    x * STEP;


                const py =
                    CENTER -
                    y * STEP;


                if(!started){

                    ctx.moveTo(
                        px,
                        py
                    );

                    started = true;

                }else{

                    ctx.lineTo(
                        px,
                        py
                    );

                }

            }


            ctx.stroke();

        }
    );


    // ========================================================
    // スキャンビーム
    // ========================================================

    scanBeams.forEach(
        func => {

            const shotIndex =
                shots.indexOf(func);


            if(
                shotIndex === selectedShot
            ){

                ctx.strokeStyle =
                    "lime";

            }else{

                ctx.strokeStyle =
                    "yellow";

            }


            ctx.lineWidth =
                3;


            const px =
                CENTER +
                func.x * STEP;


            ctx.beginPath();


            ctx.moveTo(
                px,
                0
            );


            ctx.lineTo(
                px,
                SIZE
            );


            ctx.stroke();

        }
    );

}


// ============================================================
// 拠点描画
// ============================================================

function drawPoints(){

    // ========================================================
    // 小型拠点
    // ========================================================

    points.forEach(
        point => {

                        // ------------------------------------------------
            // ゲーム終了後
            // 残っている拠点を表示
            // ------------------------------------------------

            if(
                showRemainingBases &&
                !point.destroyed
            ){

                const px =
                    CENTER +
                    point.x * STEP;


                const py =
                    CENTER -
                    point.y * STEP;


                ctx.beginPath();


                ctx.arc(
                    px,
                    py,
                    8,
                    0,
                    Math.PI * 2
                );


                ctx.strokeStyle =
                    "hotpink";


                ctx.lineWidth =
                    3;


                ctx.stroke();


                return;

            }

            // ------------------------------------------------
            // 非表示
            // ------------------------------------------------

            if(!point.visible){

                return;

            }


            // ------------------------------------------------
            // スキャンで発見しただけ
            // 黄色い縁だけの丸
            // ------------------------------------------------

            if(
                point.scanned &&
                !point.destroyed
            ){

                const px =
                    CENTER +
                    point.x * STEP;


                const py =
                    CENTER -
                    point.y * STEP;


                ctx.beginPath();


                ctx.arc(
                    px,
                    py,
                    8,
                    0,
                    Math.PI * 2
                );


                ctx.strokeStyle =
                    "yellow";


                ctx.lineWidth =
                    3;


                ctx.stroke();


                return;

            }


            // ------------------------------------------------
            // 破壊済み
            // ------------------------------------------------

            if(point.destroyed){

                drawPoint(
                    point,
                    "red"
                );

                return;

            }


            // ------------------------------------------------
            // その他
            // ------------------------------------------------

            drawPoint(
                point,
                "red"
            );

        }
    );


    // ========================================================
    // 大型拠点
    // ========================================================

    largeBases.forEach(
        base => {

                    // ------------------------------------------------
        // ゲーム終了後
        // 残っている大型拠点を表示
        // ------------------------------------------------

        if(
            showRemainingBases &&
            !base.destroyed
        ){

            drawLargeBase(
                base,
                "hotpink"
            );

            return;

        }
        
            // ------------------------------------------------
            // 配置中
            // ------------------------------------------------

            if(placing){

                drawLargeBase(
                    base
                );

                return;

            }


            // ------------------------------------------------
            // 発見済み
            // ------------------------------------------------

            if(base.visible){

                drawLargeBase(
                    base
                );

                return;

            }


            // ------------------------------------------------
            // 破壊済み
            // ------------------------------------------------

            if(base.destroyed){

                drawLargeBase(
                    base
                );

                return;

            }


            // ------------------------------------------------
            // 未発見・未破壊
            // 命中した頂点だけ表示
            // ------------------------------------------------

            base.points.forEach(
                point => {

                    if(!point.hit){

                        return;

                    }


                    drawPoint(
                        point,
                        "blue"
                    );

                }
            );

        }
    );

}


// ============================================================
// 大型拠点描画
// ============================================================

function drawLargeBase(
    base,
    customColor = null
){

    const baseColor =
        customColor !== null
            ? customColor
            : (
                base.destroyed
                    ? "red"
                    : "blue"
            );


    const p1 =
        base.points[0];

    const p2 =
        base.points[1];

    const p3 =
        base.points[2];

    const p4 =
        base.points[3];


    const x1 =
        CENTER +
        p1.x * STEP;


    const y1 =
        CENTER -
        p1.y * STEP;


    const x2 =
        CENTER +
        p2.x * STEP;


    const y2 =
        CENTER -
        p2.y * STEP;


    const x3 =
        CENTER +
        p3.x * STEP;


    const y3 =
        CENTER -
        p3.y * STEP;


    const x4 =
        CENTER +
        p4.x * STEP;


    const y4 =
        CENTER -
        p4.y * STEP;


    // ========================================================
    // 枠
    // ========================================================

    ctx.strokeStyle =
        baseColor;

    ctx.lineWidth =
        2;


    ctx.beginPath();


    ctx.moveTo(
        x1,
        y1
    );


    ctx.lineTo(
        x2,
        y2
    );


    ctx.lineTo(
        x4,
        y4
    );


    ctx.lineTo(
        x3,
        y3
    );


    ctx.closePath();


    ctx.stroke();


    // ========================================================
    // 4頂点
    // ========================================================

    base.points.forEach(
        point => {

            drawPoint(
                point,
                baseColor
            );

        }
    );

}


// ============================================================
// 命中判定
// ============================================================

function checkHit(func){

    // ========================================================
    // 小型拠点
    // ========================================================

    points.forEach(
        point => {

            if(point.destroyed){

                return;

            }


            const y =
                func.a * point.x +
                func.b;


            // ------------------------------------------------
            // 点そのものに命中
            // ------------------------------------------------

            if(
                Math.abs(
                    y - point.y
                ) < 0.01
            ){

                point.destroyed =
                    true;

                point.visible =
                    true;

                point.scanned =
                    false;

                score += 1;

            }

        }
    );


    // ========================================================
    // 大型拠点
    // ========================================================

    largeBases.forEach(
        base => {

            if(base.destroyed){

                return;

            }


            // ------------------------------------------------
            // 各頂点への命中
            // ------------------------------------------------

            base.points.forEach(
                point => {

                    if(point.hit){

                        return;

                    }


                    const y =
                        func.a * point.x +
                        func.b;


                    if(
                        Math.abs(
                            y - point.y
                        ) < 0.01
                    ){

                        point.hit =
                            true;

                    }

                }
            );


            // ------------------------------------------------
            // 2点命中
            // ------------------------------------------------

            const hitCount =
                base.points.filter(
                    point =>
                        point.hit
                ).length;


            if(hitCount >= 2){

                base.destroyed =
                    true;

                score += 5;


                // --------------------------------------------
                // 大型拠点破壊でスキャン権+1
                // --------------------------------------------

                scan++;


                document.getElementById(
                    "scan"
                ).textContent =
                    scan;

            }

        }
    );

}


