// ============================================================

function useTurn(cost){

    // ゲーム終了済み
    if(gameEnded){

        alert(
            "ゲームは終了しています"
        );

        return false;
    }


    // 残りターン不足
    if(
        turn + cost >
        MAX_TURNS
    ){

        alert(
            `残りターンが足りません\n現在：${turn} / ${MAX_TURNS}`
        );

        return false;
    }


    // ターン消費
    turn += cost;


    // 表示更新
    document.getElementById(
        "turn"
    ).textContent = turn;


    // 最大ターン到達
if(
    turn >=
    MAX_TURNS
){

    gameEnded = true;


    // --------------------------------------------------------
    // 残りの拠点確認ボタンを表示
    // --------------------------------------------------------

    const revealRemainingBtn =
        document.getElementById(
            "revealRemainingBtn"
        );


    if(revealRemainingBtn){

        revealRemainingBtn.style.display =
            "block";

    }


    alert(
        "ゲーム終了！"
    );

}

    return true;
}


